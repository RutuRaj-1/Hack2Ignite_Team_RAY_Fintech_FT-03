# ─────────────────────────────────────────────────────────────────────────────
# Context & Educational Lesson Endpoints
# ─────────────────────────────────────────────────────────────────────────────

@router.get(
    "/context",
    response_model=FinancialContext,
    summary="Get structured financial context for current business",
)
async def get_coach_context(
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> FinancialContext:
    business = await _require_business(current_user, db)
    service = CoachService(db)
    return await service.build_financial_context(business.id)


@router.get(
    "/education",
    response_model=EducationalCardsResponse,
    summary="Get 7 contextual educational financial literacy cards",
    description=(
        "Returns curated lesson cards covering Cash Flow, EMI, Interest, "
        "Repayment Burden, Revenue Consistency, Expense Management, and Transaction Risk."
    ),
)
async def get_educational_cards() -> EducationalCardsResponse:
    service = CoachService(None)  # No DB needed for static educational cards
    cards = service.get_educational_cards()
    return EducationalCardsResponse(cards=cards)


# ─────────────────────────────────────────────────────────────────────────────
# Specific Contextual Explanations
# ─────────────────────────────────────────────────────────────────────────────

@router.post(
    "/explain-fraud",
    response_model=ExplainFraudResponse,
    summary="Explain why a transaction was flagged",
)
async def explain_fraud(
    body: ExplainFraudRequest,
    current_user: User = Depends(get_current_user),
) -> ExplainFraudResponse:
    ai = AIService()
    explanation = ai.explain_fraud_alert(body.model_dump())
    recommendation = (
        "Verify the merchant counterparty and payment timestamp. If legitimate, "
        "continue standard operations to establish historical baseline."
    )
    return ExplainFraudResponse(
        explanation=explanation,
        recommendation=recommendation,
        risk_level=body.risk_level,
    )


@router.post(
    "/explain-scheme",
    response_model=ExplainSchemeResponse,
    summary="Explain government scheme alignment",
)
async def explain_scheme(
    body: ExplainSchemeRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> ExplainSchemeResponse:
    business = await _require_business(current_user, db)
    ai = AIService()
    summary = ai.explain_scheme(body.model_dump(), {"business_name": business.business_name})
    return ExplainSchemeResponse(
        summary=summary,
        why_it_matches=f"Aligns with your MSME operating turnover and sector requirements with a {body.match_score}% match score.",
        next_steps=[
            "Gather Udyam registration and recent GST returns",
            "Verify eligibility criteria on the official portal",
            "Submit application through an accredited lending institution",
        ],
    )
